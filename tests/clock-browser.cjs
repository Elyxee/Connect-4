const path = require('node:path');
const assert = require('node:assert/strict');
const { createServer, launch, shotDir } = require('./helpers/browser.cjs');
const out = shotDir('clock');
const server = createServer();

(async () => {
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const browser = await launch();
  try {
    const page = await browser.newPage({viewport:{width:1194,height:834},serviceWorkers:'block'});
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/`);
    await page.waitForSelector('#bootScreen',{state:'hidden'});
    await page.click('#home-new');await page.waitForSelector('#cloudTransition',{state:'hidden'});
    await page.clock.install();
    await page.evaluate(()=>document.fonts.ready);
    await page.waitForFunction(()=>document.querySelector('#gameClock .clock__art img')?.complete);
    await page.clock.runFor(500);
    await page.evaluate(() => {
      const applyMove = GameState.prototype.applyMove;
      GameState.prototype.applyMove = function(col) {
        window.clockTestGame = this;
        return applyMove.call(this,col);
      };
    });
    const clock = page.locator('#gameClock');
    const state = () => clock.getAttribute('data-state');
    const time = color => page.locator(`.clock__time--${color}`).textContent();
    const ply = async () => {
      await page.waitForFunction(()=>!window.clockTestGame || Number(document.querySelector('#stepNow').textContent)===clockTestGame.current.ply);
      return Number(await page.locator('#stepNow').textContent());
    };
    const drop = async col => {
      const b = await page.locator('#boardCanvas').boundingBox();
      await page.mouse.click(b.x+(col+.5)*b.width/7,b.y+b.height*.8);
    };
    await page.click('[data-enter-mode="clock"]');
    await drop(0);
    assert.equal(await ply(),0);
    await page.screenshot({path:path.join(out,'ipad-setup.png')});
    await page.click('[data-clock-preset="5+5"]');
    await page.clock.runFor(750);
    assert.equal(await state(),'red-active');
    await page.waitForTimeout(750);
    await page.screenshot({path:path.join(out,'ipad-red.png')});
    await page.clock.fastForward(1000);
    await drop(0);
    assert.equal(await state(),'yellow-active');
    const frozenRed = await time('red');
    await page.clock.runFor(750);
    await page.waitForTimeout(750);
    await page.screenshot({path:path.join(out,'ipad-yellow.png')});
    await page.clock.fastForward(1200);
    assert.equal(await time('red'),frozenRed);
    await page.click('#btnPrev');
    assert.equal(await state(),'yellow-active');
    assert.equal(await time('red'),frozenRed);
    assert.equal(await page.locator('.clock__return').isVisible(),true);
    await drop(5);
    assert.equal(await state(),'yellow-active');
    assert.equal(await time('red'),frozenRed);
    assert.equal(await ply(),0);
    await drop(0); // Even clicking the existing continuation is not history navigation.
    assert.equal(await ply(),0);
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),2);
    assert.equal(await page.locator('.ghostRow--show').count(),0);
    assert.equal(await page.locator('.analysis__side.is-turn').count(),0);
    await page.click('.clock__return');
    assert.equal(await ply(),1);
    await page.click('#btnReview');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='0');
    assert.equal(await ply(),0);
    assert.equal(await state(),'yellow-active');
    await page.click('.clock__return');
    for (const col of [1,0,1,0,1,0]) await drop(col);
    assert.equal(await state(),'full-red');
    assert.equal(await page.locator('.clock__reason').textContent(),'WIN BY CONNECT FOUR');
    assert.equal(await page.locator('.clock__caption').isVisible(),false);
    assert.equal(await page.locator('.clock__winner').textContent(),'RED');
    const resultLayout = await page.locator('.clock__result').evaluate((result) => {
      const box = result.getBoundingClientRect();
      const read = (selector) => {
        const element = result.querySelector(selector);
        const rect = element.getBoundingClientRect();
        return { centerX: rect.left + rect.width / 2, centerY: rect.top + rect.height / 2, fontSize: parseFloat(getComputedStyle(element).fontSize) };
      };
      return { box: { centerX: box.left + box.width / 2, centerY: box.top + box.height / 2 }, winner: read('.clock__winner'), reason: read('.clock__reason'), time: read('.clock__result-time') };
    });
    assert.ok(Math.abs(resultLayout.winner.centerX-resultLayout.box.centerX)<1);
    assert.ok(Math.abs(resultLayout.reason.centerX-resultLayout.box.centerX)<1);
    assert.ok(Math.abs(resultLayout.time.centerX-resultLayout.box.centerX)<1);
    assert.ok(Math.abs(resultLayout.reason.centerY-resultLayout.box.centerY)<1);
    assert.ok(resultLayout.winner.fontSize < resultLayout.time.fontSize && resultLayout.time.fontSize < resultLayout.reason.fontSize);
    assert.equal(await ply(),7);
    await page.clock.runFor(800);
    await page.waitForTimeout(750);
    await page.screenshot({path:path.join(out,'ipad-connect-four.png')});
    const winTime = await page.locator('.clock__result-time').textContent();
    await page.clock.fastForward(10000);
    assert.equal(await page.locator('.clock__result-time').textContent(),winTime);
    await drop(2);
    assert.equal(await ply(),7);
    await page.click('#btnPrev');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='6');
    await drop(4);
    assert.equal(await ply(),6);
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),8);
    assert.equal(await state(),'full-red');
    assert.equal(await page.locator('.clock__result-time').textContent(),winTime);
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    assert.equal(await state(),'setup');
    await drop(3);
    assert.equal(await ply(),0);
    await page.click('[data-clock-preset="10+3"]');
    await page.clock.fastForward(600001);
    assert.equal(await state(),'full-yellow');
    assert.equal(await page.locator('.clock__reason').textContent(),'WIN ON TIME');
    await drop(4);
    assert.equal(await ply(),0);
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),1);
    assert.equal(await page.locator('.clock__result-time').textContent(),'10:00');
    await drop(0);
    assert.equal(await ply(),0);
    await page.clock.runFor(800);
    await page.waitForTimeout(750);
    await page.screenshot({path:path.join(out,'ipad-timeout.png')});
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    await page.click('[data-clock-preset="15+0"]');
    for (let i=0;i<6;i++) await drop(0);
    const before = await time('yellow');
    await drop(0);
    assert.equal(await ply(),6);
    assert.equal(await state(),'red-active');
    assert.equal(await time('yellow'),before);
    await page.click('#btnEdit');
    await drop(3);
    assert.equal(await ply(),6);
    assert.equal(await state(),'red-active');
    await page.click('#btnEraser');
    await drop(3);
    assert.equal(await ply(),6);
    await page.click('#btnEdit');
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    await page.click('[data-clock-preset="15+0"]');
    for (const col of [0,1,0,1,2,1,2,1]) await drop(col);
    assert.equal(await state(),'full-yellow');
    assert.equal(await page.locator('.clock__winner').textContent(),'YELLOW');
    assert.equal(await page.locator('.clock__reason').textContent(),'WIN BY CONNECT FOUR');
    assert.equal(await page.locator('.clock__caption').isVisible(),false);
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    await page.click('[data-clock-preset="5+5"]');
    await drop(0);
    await page.click('#btnPrev');
    await page.clock.fastForward(300001);
    assert.equal(await state(),'full-red');
    assert.equal(await page.locator('.clock__reason').textContent(),'WIN ON TIME');
    await drop(4);
    assert.equal(await ply(),0);
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),2);
    await page.click('.clock__return');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='1');
    assert.equal(await ply(),1);
    await drop(1);
    assert.equal(await ply(),1);
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    await page.setViewportSize({width:390,height:844});
    await page.clock.runFor(400);
    await page.screenshot({path:path.join(out,'phone-setup.png'),fullPage:true});
    for (const button of await page.locator('.clock__preset').all()) {
      assert.equal(await button.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
    }
    await page.click('[data-clock-preset="5+5"]');
    await page.clock.runFor(750);
    await page.waitForTimeout(750);
    await page.screenshot({path:path.join(out,'phone-red.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.setViewportSize({width:1720,height:1194});
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.click('#btnNew');
    await page.click('[data-enter-mode="clock"]');
    await page.click('[data-clock-preset="5+5"]');
    await drop(2);
    assert.equal(await state(),'yellow-active');
    assert.equal(await page.locator('.clock__image-layer').count(),1);
    assert.equal(await page.locator('.clock__time--red').evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
    const frozen = await time('red');
    await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='0');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='1');
    assert.equal(await state(),'yellow-active');
    assert.equal(await time('red'),frozen);
    // A held pointer must not create a move after history navigation.
    let b = await page.locator('#boardCanvas').boundingBox();
    await page.mouse.move(b.x+b.width*.5,b.y+b.height*.8);
    await page.mouse.down();
    await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='0');
    await page.mouse.up();
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),2);
    await page.click('#btnEnd');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='1');
    // Starting on a read-only board and returning live while held must not drop either.
    await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='0');
    await page.mouse.move(b.x+b.width*.5,b.y+b.height*.8);
    await page.mouse.down();
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='1');
    await page.mouse.up();
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),2);
    // Pointer down/up across New + a new time preset belongs to the old game.
    await page.mouse.down();
    await page.evaluate(()=>{ document.querySelector('#btnNew').click(); document.querySelector('[data-enter-mode="clock"]').click(); });
    await page.evaluate(()=>document.querySelector('[data-clock-preset="5+5"]').click());
    await page.mouse.up();
    await page.waitForFunction(()=>document.querySelector('#stepNow').textContent==='0');
    assert.equal(await state(),'red-active');
    await drop(3);
    assert.equal(await ply(),1);
    assert.equal(await page.evaluate(()=>clockTestGame.nodeById.size),2);
    assert.equal(await state(),'yellow-active');
    await page.screenshot({path:path.join(out,'desktop-yellow.png')});
    assert.deepEqual(errors,[]);
    console.log('PASS: setup, presets, real commits, rapid wins, invalid/full column, read-only history/review/results, pointer/navigation/reset races, drawing/eraser, timeouts, phone layout; no JS errors.');
  } finally {
    await browser.close();
    await new Promise(resolve=>server.close(resolve));
  }
})().catch(error=>{console.error(error);server.close();process.exitCode=1;});
